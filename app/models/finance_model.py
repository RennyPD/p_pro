class BillingPlan(Base):
    """Recurring or one-off charge applied to a group of students (e.g. monthly tuition).

    Each cycle is a calendar month ("YYYY-MM"): a monthly plan has one cycle per
    month between start_month and end_month; a single plan has only start_month.
    Ready to carry institution_id (the unique name would become per institution).
    """

    __tablename__ = "billing_plans"
    billing_plan_id: Mapped[int] = mapped_column(primary_key=True)
    name: Mapped[str] = mapped_column(String(120), unique=True)
    charge_description: Mapped[str] = mapped_column(String(150))
    billing_concept_id: Mapped[int | None] = mapped_column(
        ForeignKey("billing_concepts.billing_concept_id"), nullable=True
    )
    amount: Mapped[Decimal] = mapped_column(MONEY)
    frequency: Mapped[str] = mapped_column(String(20), default="monthly")
    start_month: Mapped[date] = mapped_column(Date)
    end_month: Mapped[date] = mapped_column(Date)
    due_day: Mapped[int] = mapped_column(Integer, default=5)
    period_id: Mapped[int | None] = mapped_column(
        ForeignKey("academic_periods.period_id"), nullable=True
    )
    active: Mapped[bool] = mapped_column(default=True)
    created_by: Mapped[int | None] = mapped_column(ForeignKey("users.user_id"), nullable=True)
    created_at: Mapped[datetime] = mapped_column(
        DateTime, default=lambda: datetime.now(UTC).replace(tzinfo=None)
    )
    targets: Mapped[list["BillingPlanTarget"]] = relationship(
        "BillingPlanTarget", cascade="all, delete-orphan"
    )


class BillingPlanTarget(Base):
    """Who a plan applies to: a career (or school grade), a student, or an exclusion."""

    __tablename__ = "billing_plan_targets"
    __table_args__ = (
        UniqueConstraint(
            "billing_plan_id", "kind", "career_id", "student_id", name="uq_plan_target"
        ),
    )
    billing_plan_target_id: Mapped[int] = mapped_column(primary_key=True)
    billing_plan_id: Mapped[int] = mapped_column(ForeignKey("billing_plans.billing_plan_id"))
    kind: Mapped[str] = mapped_column(String(20))  # career | student | exclude
    career_id: Mapped[int | None] = mapped_column(ForeignKey("careers.career_id"), nullable=True)
    student_id: Mapped[int | None] = mapped_column(ForeignKey("students.student_id"), nullable=True)


