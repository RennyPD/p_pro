# Money: exact decimal with cents, in the database and in Python (CLAUDE.md, rule 7).
MONEY = Numeric(12, 2)


class StudentAccount(TenantMixin, Base):
    __tablename__ = "student_accounts"

    student_account_id: Mapped[int] = mapped_column(primary_key=True)
    student_id: Mapped[int] = mapped_column(ForeignKey("students.student_id"), unique=True)
    cutoff_day: Mapped[int] = mapped_column(Integer, default=15)
    due_day: Mapped[int] = mapped_column(Integer, default=30)
    ledger_version: Mapped[int] = mapped_column(Integer, default=0, server_default="0")
    student: Mapped["Student"] = relationship("Student")
    charges: Mapped[list["Charge"]] = relationship("Charge", cascade="all, delete-orphan")
    payments: Mapped[list["Payment"]] = relationship("Payment", cascade="all, delete-orphan")
    adjustments: Mapped[list["FinancialAdjustment"]] = relationship(
        "FinancialAdjustment", cascade="all, delete-orphan"
    )
    payment_plans: Mapped[list["PaymentPlan"]] = relationship(
        "PaymentPlan", cascade="all, delete-orphan"
    )


class Charge(TenantMixin, Base):
    __tablename__ = "charges"
    __table_args__ = (
        Index("idx_charges_account_due", "student_account_id", "due_date"),
        # A billing plan charges each account at most once per cycle, even under
        # concurrent runs. Manual charges (no plan) are not affected.
        UniqueConstraint(
            "student_account_id",
            "billing_plan_id",
            "billing_cycle",
            name="uq_charges_plan_cycle",
        ),
    )

    charge_id: Mapped[int] = mapped_column(primary_key=True)
    student_account_id: Mapped[int] = mapped_column(
        ForeignKey("student_accounts.student_account_id")
    )
    description: Mapped[str] = mapped_column(String(200))
    amount: Mapped[Decimal] = mapped_column(MONEY)
    due_date: Mapped[date] = mapped_column(Date)
    created_by: Mapped[int | None] = mapped_column(ForeignKey("users.user_id"), nullable=True)
    status: Mapped[str] = mapped_column(String(20), default="posted", server_default="posted")
    reversal_reason: Mapped[str | None] = mapped_column(String(250), nullable=True)
    created_at: Mapped[datetime] = mapped_column(
        DateTime, default=lambda: datetime.now(UTC).replace(tzinfo=None)
    )
    # Set when the charge was generated by a billing plan; cycle is "YYYY-MM".
    billing_plan_id: Mapped[int | None] = mapped_column(
        ForeignKey("billing_plans.billing_plan_id"), nullable=True
    )
    billing_cycle: Mapped[str | None] = mapped_column(String(7), nullable=True)


