  admission: "Admisión", alert: "Caso", announcement: "Aviso", approval: "Solicitud", assessment: "Evaluación",
  classroom: "Aula", document: "Documento", enrollment: "Selección", equivalence: "Equivalencia", meeting: "Reunión",
